#!/bin/bash
# Preserve identity and generate machine-local pager settings.
GIT_GENERATED="$HOME/.gitconfig.envup"

_git_generated_owned() {
    local owner
    [[ ! -L "$GIT_GENERATED" && -f "$GIT_GENERATED" &&
       ! -L "$ENVUP_STATE_DIR/git-generated" && -f "$ENVUP_STATE_DIR/git-generated" ]] || return 1
    IFS= read -r owner < "$ENVUP_STATE_DIR/git-generated" || return 1
    [[ "$owner" == "# envup repo: $ENVUP_HOME" ]] && cmp -s "$GIT_GENERATED" "$ENVUP_STATE_DIR/git-generated"
}

_git_write_generated() {
    local delta tmp record_tmp bak="" record="$ENVUP_STATE_DIR/git-generated"
    delta="$(bin_path delta 2>/dev/null || true)"

    if [[ "${ENVUP_DRY_RUN:-0}" == 1 ]]; then
        if [[ -n "$delta" ]]; then log_info "[dry-run] would enable the delta pager in $GIT_GENERATED"
        else log_info "[dry-run] would write $GIT_GENERATED (delta not installed here)"; fi
        return 0
    fi

    # A redirected generated file must never write through into shared recipes.
    if [[ -L "$GIT_GENERATED" || ( -e "$GIT_GENERATED" && ! -f "$GIT_GENERATED" ) ]]; then
        log_error "$GIT_GENERATED is not a regular file; keep its contents in a private override instead"
        return 1
    fi
    if [[ -L "$record" || ( -e "$record" && ! -f "$record" ) ]]; then
        log_error "generated-config record is not a regular file: $record"
        return 1
    fi
    mkdir -p "$ENVUP_STATE_DIR" || return 1
    tmp="$(mktemp "$ENVUP_STATE_DIR/git-config.XXXXXX")" || return 1

    {
        printf '# envup repo: %s\n' "$ENVUP_HOME"
        echo "# Generated by 'envup install git' — do not edit, it is rewritten"
        echo "# every install. Per-machine settings you want to keep belong in"
        echo "# modules/git/files/hosts/<hostname>.gitconfig (committed) or"
        echo "# ~/.gitconfig.local (private). Both are included after this file."
        if [[ -n "$delta" ]]; then
            printf '\n[pager]\n\tdiff = %s\n\tlog = %s\n\treflog = %s\n\tshow = %s\n' \
                   "$delta" "$delta" "$delta" "$delta"
            printf '\n[interactive]\n\tdiffFilter = %s --color-only\n' "$delta"
        fi
    } > "$tmp" || { rm -f "$tmp"; log_error "could not prepare $GIT_GENERATED"; return 1; }
    record_tmp="$(mktemp "$ENVUP_STATE_DIR/git-record.XXXXXX")" || { rm -f "$tmp"; return 1; }
    if ! cp "$tmp" "$record_tmp"; then
        rm -f "$tmp" "$record_tmp"
        return 1
    fi
    # Unrecorded legacy output and user edits both need a recoverable copy.
    if [[ -e "$GIT_GENERATED" ]] && ! _git_generated_owned; then
        bak="$(backup_path "$GIT_GENERATED")"
        if [[ -e "$bak" || -L "$bak" ]] || ! mkdir -p "${bak%/*}" || ! mv "$GIT_GENERATED" "$bak"; then
            rm -f "$tmp" "$record_tmp"
            log_error "could not back up $GIT_GENERATED"
            return 1
        fi
        log_info "backup: $GIT_GENERATED -> $bak"
    fi
    if ! mv "$tmp" "$GIT_GENERATED"; then
        [[ -n "$bak" ]] && mv "$bak" "$GIT_GENERATED"
        rm -f "$tmp" "$record_tmp"
        return 1
    fi
    mv "$record_tmp" "$record" || { rm -f "$record_tmp"; return 1; }

    if [[ -n "$delta" ]]; then
        log_success "delta found — enabled as git's pager"
    else
        log_info "delta not installed here; git keeps its default pager"
    fi
}

pre_install() {
    # Read identity before ~/.gitconfig is replaced by a managed link.
    _GIT_CARRY_NAME="$(git config --global user.name  2>/dev/null || true)"
    _GIT_CARRY_MAIL="$(git config --global user.email 2>/dev/null || true)"
    return 0
}

post_install() {
    _git_write_generated || return 1

    local cfg="$HOME/.gitconfig.local"
    if [[ "${ENVUP_DRY_RUN:-0}" == 1 ]]; then
        log_info "[dry-run] would ensure $cfg exists"; return 0
    fi
    [[ -e "$cfg" || -L "$cfg" ]] && return 0

    cat > "$cfg" <<EOF || return 1
# Per-machine git identity — NOT in the repo. Loaded last via [include].
[user]
    name  = ${_GIT_CARRY_NAME:-YOUR NAME}
    email = ${_GIT_CARRY_MAIL:-your.email@example.com}
EOF
    if [[ -n "$_GIT_CARRY_NAME" && -n "$_GIT_CARRY_MAIL" ]]; then
        log_success "created $cfg (kept the identity this machine already had)"
    else
        log_warn "created $cfg — set a real name/email or 'git commit' will refuse to run"
        log_hint "edit it: \$EDITOR $cfg"
    fi
}

post_uninstall() {
    if ! _git_generated_owned; then
        log_info "$GIT_GENERATED kept (not unchanged envup output)"
    elif [[ "${ENVUP_DRY_RUN:-0}" == 1 ]]; then
        log_info "[dry-run] would remove owned $GIT_GENERATED"
    else
        rm -f "$GIT_GENERATED" || return 1
        rm -f "$ENVUP_STATE_DIR/git-generated" || return 1
    fi
    # shellcheck disable=SC2088  # literal ~ is display text, not a path to expand
    log_info "~/.gitconfig.local (your identity) kept"
    return 0
}
